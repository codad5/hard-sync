use tauri::{
    menu::{Menu, MenuItem, PredefinedMenuItem},
    tray::TrayIconBuilder,
    Manager,
};

mod commands;

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    tauri::Builder::default()
        .manage(commands::AppWatchers::default())
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_shell::init())
        .setup(|app| {
            // System tray
            let show = MenuItem::with_id(app, "show", "Show hard-sync", true, None::<&str>)?;
            let stop_all = MenuItem::with_id(app, "stop_all", "Stop all watchers", true, None::<&str>)?;
            let quit = MenuItem::with_id(app, "quit", "Quit hard-sync", true, None::<&str>)?;
            let sep = PredefinedMenuItem::separator(app)?;
            let menu = Menu::with_items(app, &[&show, &stop_all, &sep, &quit])?;

            let tray = TrayIconBuilder::new();
            // macOS menu-bar icons are "template images": black + transparency,
            // recoloured by the system to match light/dark menu bars like every
            // other menu-bar icon. Windows/Linux trays expect the coloured logo.
            // (Generated by icons/make_tray_icon.py from logo.svg.)
            #[cfg(target_os = "macos")]
            let tray = tray
                .icon(tauri::image::Image::from_bytes(include_bytes!("../icons/tray-template.png"))?)
                .icon_as_template(true);
            #[cfg(not(target_os = "macos"))]
            let tray = tray.icon(app.default_window_icon().unwrap().clone());

            tray
                .menu(&menu)
                .tooltip("hard-sync")
                .on_menu_event(|app, event| match event.id.as_ref() {
                    "show" => show_window(app),
                    // Pause syncing without quitting the app
                    "stop_all" => commands::stop_every_watcher(app),
                    "quit" => app.exit(0),
                    _ => {}
                })
                .on_tray_icon_event(|tray, event| {
                    // Left-click on tray icon toggles the window
                    if let tauri::tray::TrayIconEvent::Click {
                        button: tauri::tray::MouseButton::Left,
                        ..
                    } = event
                    {
                        show_window(tray.app_handle());
                    }
                })
                .build(app)?;

            Ok(())
        })
        .invoke_handler(tauri::generate_handler![
            commands::cmd_list_pairs,
            commands::cmd_add_pair,
            commands::cmd_remove_pair,
            commands::cmd_set_source,
            commands::cmd_trigger_sync,
            commands::cmd_list_drives,
            commands::cmd_platform,
            commands::cmd_watcher_status,
            commands::cmd_start_watcher,
            commands::cmd_stop_watcher,
            commands::cmd_watcher_log,
        ])
        // Closing the window hides it: hard-sync keeps running (and watching)
        // in the menu bar / system tray until Quit.
        .on_window_event(|window, event| {
            if let tauri::WindowEvent::CloseRequested { api, .. } = event {
                api.prevent_close();
                let _ = window.hide();
            }
        })
        .build(tauri::generate_context!())
        .expect("error while building tauri application")
        .run(|app, event| match event {
            // macOS: clicking the Dock icon opens the window.
            #[cfg(target_os = "macos")]
            tauri::RunEvent::Reopen { .. } => show_window(app),
            tauri::RunEvent::Exit => commands::stop_all(&app.state::<commands::AppWatchers>()),
            _ => {}
        });
}

fn show_window(app: &tauri::AppHandle) {
    if let Some(window) = app.get_webview_window("main") {
        let _ = window.show();
        let _ = window.set_focus();
    }
}
